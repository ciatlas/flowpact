const contractInputSchema = z.strictObject({
  type: z.optional(z.string()),
  required: z.boolean(),
  default: z.optional(z.json()),
  description: z.optional(z.string()),
  options: z.optional(z.array(z.string())),
});

const contractCallSchema = z.strictObject({
  job: z.string(),
  uses: z.string(),
  with: z.optional(z.record(z.string(), z.string())),
  secrets: z.optional(z.union([z.literal('inherit'), z.record(z.string(), z.string())])),
  needs: z.optional(z.array(z.string())),
  matrix: z.optional(
    z.strictObject({
      combinations: z.number().check(z.int()),
      keys: z.array(z.string()),
      exact: z.boolean(),
    }),
  ),
});

const contractUseSchema = z.strictObject({
  job: z.optional(z.string()),
  step: z.string(),
  uses: z.string(),
  with: z.optional(z.record(z.string(), z.string())),
});

const contractConsumerSchema = z.strictObject({
  from: z.string(),
  job: z.optional(z.string()),
  step: z.optional(z.string()),
  passes: z.array(z.string()),
  reads: z.array(z.string()),
});

export const contractSchema = z.strictObject({
  $schema: z.string(),
  version: z.literal(SCHEMA_VERSIONS.contract),
  kind: z.enum(['workflow', 'action']),
  path: z.string(),
  name: z.optional(z.string()),
  triggers: z.optional(z.array(z.string())),
  interface: z.strictObject({
    /** `workflow_call` inputs for workflows, `inputs` for actions. */
    inputs: z.record(z.string(), contractInputSchema),
    /** `workflow_dispatch` inputs (workflows only). */
    dispatchInputs: z.optional(z.record(z.string(), contractInputSchema)),
    secrets: z.optional(z.record(z.string(), z.strictObject({ required: z.boolean() }))),
    outputs: z.record(
      z.string(),
      z.strictObject({ description: z.optional(z.string()), value: z.optional(z.string()) }),
    ),
  }),
  calls: z.optional(z.array(contractCallSchema)),
  uses: z.optional(z.array(contractUseSchema)),
  consumers: z.array(contractConsumerSchema),
});

export type Contract = z.infer<typeof contractSchema>;
export type ContractInput = z.infer<typeof contractInputSchema>;

export function contractJsonSchema(): Record<string, unknown> {
  return { $id: schemaUrl('contract'), title: 'flowpact contract', ...z.toJSONSchema(contractSchema) };
}

