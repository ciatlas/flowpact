export interface ExistingContract {
  file: string;
  text: string;
  contract?: Contract;
  error?: string;
}

/** Every contract file. */
export function readContracts(fs: FileSystem): Map<string, ExistingContract> {
  const out = new Map<string, ExistingContract>();
  for (const file of fs
    .walk(CONTRACTS_DIR)
    .filter((f) => f.endsWith('.contract.yml'))
    .sort()) {
    const text = fs.read(file) ?? '';
    try {
      const parsed = contractSchema.safeParse(parseYaml(text));
      out.set(
        file,
        parsed.success
          ? { file, text, contract: parsed.data }
          : {
              file,
              text,
              error: parsed.error.issues
                .map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`)
                .join('; '),
            },
      );
    } catch (err) {
      out.set(file, { file, text, error: `not valid YAML: ${(err as Error).message.split('\n')[0]}` });
    }
  }
  return out;
}

export type ContractStatus = 'create' | 'update' | 'delete' | 'unchanged';

export interface ContractPlanEntry {
  file: string;
  status: ContractStatus;
  /** The workflow/action this contract describes (absent for orphaned contracts). */
  unit?: string;
  before?: string;
  after?: string;
  changes: ContractChange[];
  /** Set when the existing file could not be read as a contract. */
  invalid?: string;
  /** Set when the unit could not be analyzed (e.g. YAML syntax errors) and its locked contract was kept. */
  skipped?: string;
}

export interface ContractPlan {
  entries: ContractPlanEntry[];
  /** Units whose contract was not regenerated because the file has YAML syntax errors. */
  skipped: string[];
  /** True when any file would be created, updated or deleted. */
  drift: boolean;
  counts: Record<ContractStatus, number>;
  breaking: number;
}

/**
 * The contract file of each unit. A contract that names a unit is matched by path even if it was written under another
 * file name, so adding `ci.yaml` next to `ci.yml` does not move `ci.yml`'s contract (and diff it against the wrong
 * workflow); other units get a file name no contract takes.
 */
function expectedFiles(
  existing: Map<string, ExistingContract>,
  units: UnitDecl[],
  dir: string,
): Map<string, UnitDecl> {
  const lockedFile = new Map<string, string>();
  for (const [file, prev] of existing) {
    const c = prev.contract;
    if (c && !lockedFile.has(c.path) && units.some((u) => u.path === c.path && u.kind === c.kind))
      lockedFile.set(c.path, file);
  }
  const expected = new Map<string, UnitDecl>();
  const taken = new Set(lockedFile.values());
  for (const unit of units) {
    const file = lockedFile.get(unit.path) ?? contractFileFor(unit, taken, dir);
    taken.add(file);
    expected.set(file, unit);
  }
  return expected;
}

/** The regenerated consumers, with the entries of callers that do not parse taken from the locked contract. */
const withBrokenConsumers = (current: Consumer[], locked: Consumer[], broken: Set<string>): Consumer[] =>
  [...current.filter((c) => !broken.has(c.from)), ...locked.filter((c) => broken.has(c.from))].sort(
    byConsumer,
  );

/** The entry of a unit that parses: its contract regenerated, and compared with the locked one when there is one. */
function regeneratedEntry(
  index: ProjectIndex,
  file: string,
  unit: UnitDecl,
  prev: ExistingContract | undefined,
  broken: Set<string>,
): ContractPlanEntry {
  const contract = buildContract(index, unit);
  if (broken.size && prev?.contract)
    contract.consumers = withBrokenConsumers(contract.consumers, prev.contract.consumers, broken);
  const after = serializeContract(contract);
  if (!prev) return { file, status: 'create', unit: unit.path, after, changes: [] };
  // Checkouts with core.autocrlf convert line endings; the content is what matters.
  if (normalizeContractText(prev.text) === after)
    return { file, status: 'unchanged', unit: unit.path, before: prev.text, after, changes: [] };
  return {
    file,
    status: 'update',
    unit: unit.path,
    before: prev.text,
    after,
    changes: prev.contract ? diffContracts(prev.contract, contract) : [],
    ...(prev.error ? { invalid: prev.error } : {}),
  };
}

/** The entry of a contract file that no unit produces any more. */
const orphanEntry = (file: string, prev: ExistingContract): ContractPlanEntry => ({
  file,
  status: 'delete',
  ...(prev.contract ? { unit: prev.contract.path } : {}),
  before: prev.text,
  changes: [],
  ...(prev.error ? { invalid: prev.error } : {}),
});

/** A plan of these entries: whether anything drifted, the count per status and the breaking changes. */
function planOf(entries: ContractPlanEntry[], skipped: string[]): ContractPlan {
  const counts: Record<ContractStatus, number> = { create: 0, update: 0, delete: 0, unchanged: 0 };
  for (const e of entries) counts[e.status]++;
  return {
    entries,
    skipped,
    drift: entries.some((e) => e.status !== 'unchanged'),
    counts,
    breaking: entries.reduce((n, e) => n + e.changes.filter((c) => c.breaking).length, 0),
  };
}

/** Compares the contracts on disk with the ones the current workflows produce. */
export function planContracts(index: ProjectIndex, fs: FileSystem): ContractPlan {
  const existing = readContracts(fs);
  const entries: ContractPlanEntry[] = [];
  const units = index.units().sort((a, b) => byCodePoint(a.path, b.path));
  const expected = expectedFiles(existing, units, CONTRACTS_DIR);
  const skipped: string[] = [];
  // A caller that does not parse cannot say what it passes; keep its consumer entries from the locked contracts.
  const broken = new Set(units.filter((u) => u.parseErrors.length > 0).map((u) => u.path));
  for (const [file, unit] of expected) {
    const prev = existing.get(file);
    // A contract derived from a file that is not valid YAML would erase its interface: keep the locked one.
    if (unit.parseErrors.length > 0) {
      skipped.push(unit.path);
      if (prev) {
        entries.push({
          file,
          status: 'unchanged',
          unit: unit.path,
          before: prev.text,
          after: prev.text,
          changes: [],
          skipped: 'YAML syntax errors',
        });
      }
      continue;
    }
    entries.push(regeneratedEntry(index, file, unit, prev, broken));
  }
  for (const [file, prev] of existing) if (!expected.has(file)) entries.push(orphanEntry(file, prev));
  entries.sort((a, b) => byCodePoint(a.file, b.file));
  return planOf(entries, skipped);
}

/** A unified diff of the plan, with git headers, applicable with `git apply` from the repository root. */
export function contractPatch(plan: ContractPlan): string {
  const parts: string[] = [];
  for (const e of plan.entries) {
    if (e.status === 'unchanged') continue;
    const before = e.status === 'create' ? '' : (e.before ?? '');
    const after = e.status === 'delete' ? '' : (e.after ?? '');
    const patch = structuredPatch(`a/${e.file}`, `b/${e.file}`, before, after, '', '', { context: 3 });
    const body = formatPatch(patch)
      .split('\n')
      .filter((_l, i, all) => i > all.findIndex((x) => x.startsWith('+++')))
      .join('\n');
    const header = [`diff --git a/${e.file} b/${e.file}`];
    if (e.status === 'create') header.push('new file mode 100644', '--- /dev/null', `+++ b/${e.file}`);
    else if (e.status === 'delete')
      header.push('deleted file mode 100644', `--- a/${e.file}`, '+++ /dev/null');
    else header.push(`--- a/${e.file}`, `+++ b/${e.file}`);
    parts.push(`${header.join('\n')}\n${body.replace(/\n*$/, '\n')}`);
  }
  return parts.join('');
}

/** A contract path that flowpact refuses to write (a symlink, or outside the repository). */
export class UnsafePathError extends Error {}

function isSymlink(abs: string): boolean {
  try {
    return lstatSync(abs).isSymbolicLink();
  } catch {
    return false;
  }
}

/**
 * The real path of `p`: its nearest existing ancestor resolved, with the rest appended. `native` gives the canonical
 * letter case on case-insensitive file systems (macOS), so another spelling of the same directory compares equal.
 */
function realpathNearest(p: string): string {
  const rest: string[] = [];
  let at = resolve(p);
  for (;;) {
    try {
      return join(realpathSync.native(at), ...rest.reverse());
    } catch {
      const parent = dirname(at);
      if (parent === at) return resolve(p);
      rest.push(basename(at));
      at = parent;
    }
  }
}

const withinOrAt = (root: string, p: string) => {
  const rel = relative(root, p);
  return rel === '' || (rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
};

/**
 * Whether `p` is `tree` or inside it, decided from canonical real paths (symlinks resolved, the file system's letter
 * case), also for paths that do not exist yet. Unlike `insideRepository`, nothing (such as `.git`) is left out: use it
 * where "inside" is the cautious answer, such as deciding that a file came with the checkout.
 */
export function pathInside(tree: string, p: string): boolean {
  return withinOrAt(realpathNearest(tree), realpathNearest(p));
}

/**
 * Whether reaching `target` follows a symbolic link that lies inside `realTree` (a tree's real path): the file itself, or
 * a directory on the way to it, also one that stays inside the tree (a link into `.git`). Links outside the tree, such
 * as `/tmp` for `/private/tmp`, are followed. Components that do not exist yet end the walk.
 */
function followsLinkIn(realTree: string, target: string): boolean {
  const abs = resolve(target);
  let at = parse(abs).root;
  for (const part of abs.slice(at.length).split(sep).filter(Boolean)) {
    const next = join(at, part);
    let link: boolean;
    try {
      link = lstatSync(next).isSymbolicLink();
    } catch {
      return false;
    }
    if (link && withinOrAt(realTree, at)) return true;
    at = link ? realpathSync.native(next) : next;
  }
  return false;
}

/**
 * Refuses to write a file (a report, a patch, a contract) at a path that leads into one of `trees` (the repository, the
 * CI workspace) and then through a symlink: one that is the file itself, a directory on the way to it (even one that
 * stays in the tree, such as a link into `.git`), or one that leads out of the tree again. A pull request can commit
 * those. Whether a path leads into a tree is decided from the real path of each of its ancestors, so no other spelling
 * of it (`/tmp` for `/private/tmp`, a symlink outside pointing in) skips the check. Paths that never enter a tree, such
 * as `$GITHUB_STEP_SUMMARY`, are written as given.
 */
export function assertSafeWritePath(abs: string, trees: string[]): void {
  const target = resolve(abs);
  const realParent = realpathNearest(dirname(target));
  const ancestors: string[] = [];
  for (let at = target; ; at = dirname(at)) {
    ancestors.push(at);
    if (dirname(at) === at) break;
  }
  for (const tree of trees) {
    const realTree = realpathNearest(tree);
    const enters = ancestors.some((a) => existsSync(a) && withinOrAt(realTree, realpathSync.native(a)));
    if (!enters && !withinOrAt(resolve(tree), target)) continue;
    if (isSymlink(target) || !withinOrAt(realTree, realParent) || followsLinkIn(realTree, target))
      throw new UnsafePathError(
        `Not writing ${abs}: it is a symlink, goes through one in ${tree}, or links outside it`,
      );
  }
}

/**
 * Refuses to write contracts into the checkout through a symlink, which could redirect a write (or delete) elsewhere.
 * Every target is checked before anything is written, so a refusal leaves the directory as it was.
 */
function assertSafeContractPaths(root: string, plan: ContractPlan): void {
  const unsafe = plan.entries
    .filter((e) => e.status !== 'unchanged')
    .map((e) => e.file)
    .filter(
      (f) =>
        isSymlink(join(root, f)) ||
        !insideRepository(root, join(root, f)) ||
        followsLinkIn(realpathNearest(root), join(root, f)),
    );
  if (unsafe.length)
    throw new UnsafePathError(
      `Not writing contracts: ${unsafe.join(', ')} ${unsafe.length === 1 ? 'is a symlink, goes through one, or links' : 'are symlinks, go through one, or link'} outside the repository`,
    );
}

/**
 * Writes (or, in the repository, deletes) one entry's file under `base`; returns whether it touched the file. An
 * output directory gets every contract but the deleted ones; the repository only the ones that changed.
 */
function applyEntry(e: ContractPlanEntry, base: string, outDir: string | undefined): boolean {
  const abs = join(base, e.file);
  if (e.status === 'delete') {
    if (outDir || !existsSync(abs)) return false;
    rmSync(abs);
    return true;
  }
  if (e.status === 'unchanged' && !outDir) return false;
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, e.after ?? '');
  return true;
}

/**
 * Applies a plan to disk. With `outDir`, files are written there (same relative paths) instead of the repository,
 * and deletions are skipped — used to hand regenerated contracts to people who cannot run flowpact. `trees` are where
 * such a write must not go through a symlink (default: the repository).
 */
export function writeContracts(
  root: string,
  plan: ContractPlan,
  outDir?: string,
  trees: string[] = [root],
): string[] {
  const written: string[] = [];
  const base = outDir ?? root;
  // An output directory inside the repository is checked like a report path, every file before any is written.
  if (outDir)
    for (const e of plan.entries) if (e.status !== 'delete') assertSafeWritePath(join(outDir, e.file), trees);
  // Contracts are written into the checkout.
  if (!outDir) assertSafeContractPaths(root, plan);
  for (const e of plan.entries) if (applyEntry(e, base, outDir)) written.push(e.file);
  return written;
}

/** Units listed as consumers in the locked or regenerated contract of an entry (callers and action users). */
export function entryConsumers(e: ContractPlanEntry): string[] {
  const out = new Set<string>();
  for (const text of [e.before, e.after]) {
    if (!text) continue;
    try {
      const data = parseYaml(text) as { consumers?: { from?: unknown }[] } | null;
      for (const c of data?.consumers ?? []) if (typeof c?.from === 'string') out.add(c.from);
    } catch {
      // An unreadable contract has no usable consumers list.
    }
  }
  return [...out];
}

/**
 * With paths (`flowpact check <paths>`, `flowpact generate <paths>`): the contracts of the targeted workflows and
 * actions, and the contracts they appear in as a consumer, since what a caller passes or reads is locked in its
 * callee's contract.
 */
export function contractsInScope(index: ProjectIndex): (e: ContractPlanEntry) => boolean {
  const { targets } = index.project;
  const targeted = (unit: string) => targets.has(index.unit(unit)?.file ?? unit);
  return (e) => (e.unit !== undefined && targeted(e.unit)) || entryConsumers(e).some(targeted);
}

/** The part of a plan that concerns `keep`: drift, counts and the patch then only cover those units. */
export function scopePlan(plan: ContractPlan, keep: (e: ContractPlanEntry) => boolean): ContractPlan {
  const entries = plan.entries.filter(keep);
  return planOf(
    entries,
    plan.skipped.filter((u) => entries.some((e) => e.unit === u)),
  );
}
