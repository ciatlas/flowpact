/** GitHub's actions.lock (actions-lock.ts): the commits it pins, where flowpact reads remote references and reports FP612. */
import { memoryFileSystem } from '@ciatlas/core';
import {
  ACTIONS_LOCK_FILE,
  fetchMissingRemotes,
  fetchRemoteEntries,
  gradeVersionChanges,
  lockedCommit,
  parseConfig,
  parseRemoteRef,
  readActionsLock,
} from '@flowpact/lint';
import { describe, expect, it } from 'vitest';
import { byCode, lint, WF, yaml } from './helpers';

const A = 'a'.repeat(40);
const B = 'b'.repeat(40);
const C = 'c'.repeat(40);

/** An actions.lock that covers ci.yml, which uses these pins, each at its commit. */
const actionsLock = (pins: Record<string, string>, version = 'v0.0.3', covered = Object.keys(pins)) => yaml`
  # This file is machine-generated by \`gh actions-lock\`.
  version: '${version}'
  workflows:
    '.github/workflows/ci.yml':
${covered.map((p) => `      - '${p}'`).join('\n')}
  dependencies:
${Object.entries(pins)
  .map(
    ([p, sha]) =>
      `    '${p}':\n      ref: '${p.split('@')[1]}'\n      commit: 'sha1-${sha}'\n      owner_id: 1\n      repo_id: 2`,
  )
  .join('\n')}
`;

const read = (text: string) => readActionsLock(memoryFileSystem({ [ACTIONS_LOCK_FILE]: text }));
const action = (raw: string) => parseRemoteRef(raw, 'action')!;

describe('readActionsLock', () => {
  it('reads the commit each pin of a covered workflow runs, with its owner and repository in any case', () => {
    const lock = read(actionsLock({ 'Octo/Setup@v2': A, 'octo/ship@v1': B }));
    expect(lock.error).toBeUndefined();
    expect(lockedCommit(lock, action('octo/setup@v2'))).toBe(A);
    expect(lockedCommit(lock, action('OCTO/SETUP@v2'))).toBe(A);
    // A reference with a path is pinned by its repository: gh actions-lock keys `owner/repo@ref`.
    expect(lockedCommit(lock, parseRemoteRef('octo/ship/.github/workflows/deploy.yml@v1', 'workflow')!)).toBe(
      B,
    );
    expect(lockedCommit(lock, action('octo/setup@v3'))).toBeUndefined();
  });

  it('reads v0.0.2 too, and no pin that no covered workflow uses', () => {
    const lock = read(actionsLock({ 'octo/setup@v2': A, 'octo/cache@v4': B }, 'v0.0.2', ['octo/setup@v2']));
    expect(lockedCommit(lock, action('octo/setup@v2'))).toBe(A);
    expect(lockedCommit(lock, action('octo/cache@v4'))).toBeUndefined();
  });

  it('uses no commit of a version it does not know, of a file that does not parse, or in another form', () => {
    expect(read(actionsLock({ 'octo/setup@v2': A }, 'v1.0.0'))).toEqual({
      file: ACTIONS_LOCK_FILE,
      error: 'version v1.0.0 is not one flowpact reads (v0.0.x)',
    });
    expect(read('version: [').error).toMatch(/^not valid YAML/);
    expect(read('- a list').error).toBe('not a workflow dependency lockfile flowpact can read');
    const sha256 = read(actionsLock({ 'octo/setup@v2': A }).replace(`sha1-${A}`, `sha256-${'f'.repeat(64)}`));
    expect(lockedCommit(sha256, action('octo/setup@v2'))).toBeUndefined();
    expect(readActionsLock(memoryFileSystem({}))).toEqual({});
  });
});

/** A stand-in for the GitHub API: tags resolve to `C`; action.yml is served at any of the commits given. */
function api(commits: Record<string, string>) {
  const asked: string[] = [];
  const fake = (async (input: string | URL) => {
    const url = new URL(String(input));
    asked.push(`${url.pathname}${url.search}`);
    if (/\/commits\//.test(url.pathname)) return new Response(C);
    const sha = url.searchParams.get('ref') ?? '';
    return commits[sha] ? new Response(commits[sha]) : new Response('', { status: 404 });
  }) as typeof globalThis.fetch;
  return { asked, options: { apiUrl: 'https://api.test', fetch: fake } };
}

const setup = (inputs: string) =>
  `name: s\ndescription: d\ninputs:\n${inputs}\nruns:\n  using: composite\n  steps: []\n`;

describe('reading remote references at the commits actions.lock pins', () => {
  it('fetches a pinned reference at its commit, without asking what its tag points at now', async () => {
    const github = api({ [A]: setup('  version: {}') });
    const r = await fetchRemoteEntries([action('octo/setup@v2')], {
      ...github.options,
      lockedCommit: () => A,
    });
    expect(r.remotes['octo/setup@v2']?.sha).toBe(A);
    expect(github.asked.some((u) => u.includes('/commits/'))).toBe(false);
  });

  it('fetches what the lockfile lacks at the commits actions.lock pins (--fetch-remotes, remotes: fetch)', async () => {
    const files = {
      [`${WF}/ci.yml`]: 'on: push\njobs:\n  b:\n    runs-on: x\n    steps:\n      - uses: octo/setup@v2\n',
      [ACTIONS_LOCK_FILE]: actionsLock({ 'octo/setup@v2': A }),
    };
    const github = api({ [A]: setup('  version: {}'), [C]: setup('  other: {}') });
    const r = await fetchMissingRemotes('/virtual/repo', memoryFileSystem(files), undefined, github.options);
    expect(r.remotes['octo/setup@v2']).toMatchObject({ sha: A, inputs: { version: {} } });
  });

  it("grades a pull request's version change at the commit the head's actions.lock pins", async () => {
    const ci = (ref: string) =>
      `on: push\njobs:\n  b:\n    runs-on: x\n    steps:\n      - uses: ${ref}\n        with: { cache: x }\n`;
    const github = api({ [A]: setup('  cache: {}'), [B]: setup('  version: {}'), [C]: setup('  cache: {}') });
    const r = await gradeVersionChanges(
      {
        root: '/virtual/repo',
        fs: memoryFileSystem({
          [`${WF}/ci.yml`]: ci('octo/setup@v2'),
          [ACTIONS_LOCK_FILE]: actionsLock({ 'octo/setup@v2': B }),
        }),
        config: parseConfig({}),
        validateSchema: false,
        repository: 'acme/repo',
      },
      memoryFileSystem({
        [`${WF}/ci.yml`]: ci('octo/setup@v1'),
        [ACTIONS_LOCK_FILE]: actionsLock({ 'octo/setup@v1': A }),
      }),
      github.options,
    );
    // @v2's tag points at C, which still takes `cache`; the pinned B does not, and B is what runs.
    expect(r.grades[0]).toMatchObject({ verdict: 'breaks', commits: { before: A, after: B } });
  });
});

describe('FP612 and actions.lock', () => {
  const LOCK = '.github/flowpact/remotes.lock.yaml';
  const files = (pinned: string, covered?: string[]) => ({
    [`${WF}/ci.yml`]: 'on: push\njobs:\n  b:\n    runs-on: x\n    steps:\n      - uses: octo/setup@v2\n',
    [LOCK]: `version: 1\nremotes:\n  octo/setup@v2:\n    sha: ${A}\n    kind: action\n`,
    [ACTIONS_LOCK_FILE]: actionsLock({ 'octo/setup@v2': pinned }, 'v0.0.3', covered),
  });
  const fp612 = (f: Record<string, string>) => byCode(lint(f), 'FP612').map((x) => x.message);

  it('reports an entry that records another commit than actions.lock runs', () => {
    expect(fp612(files(B))).toEqual([
      `${LOCK} is out of date: it records another commit than GitHub’s actions.lock runs for octo/setup@v2 (it records aaaaaaa, actions.lock bbbbbbb). Run \`flowpact remotes update\``,
    ]);
  });

  it('reports nothing when they agree, or when actions.lock does not cover the workflow', () => {
    expect(fp612(files(A))).toEqual([]);
    expect(fp612(files(B, []))).toEqual([]);
  });
});
